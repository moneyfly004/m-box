  LocaleController._();
  static final LocaleController instance = LocaleController._();

  String get lang => AppStrings.lang;

  Future<void> setLang(String l, {bool persist = true}) async {
    await AppStrings.setLang(l, persist: persist);
    notifyListeners();
  }
}
