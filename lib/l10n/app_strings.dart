  static String _lang = 'zh';

  static String get lang => _lang;

  /// 切换语言（zh/en）
  static Future<void> setLang(String l, {bool persist = true}) async {
    _lang = (l == 'en') ? 'en' : 'zh';
    if (persist) {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString('mbox_lang', _lang);
    }
  }

  /// 启动时恢复语言：优先用户手动选择；首次启动按设备系统语言自动判断（zh→中文，其它→English）
  static Future<void> restore() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final saved = prefs.getString('mbox_lang');
      if (saved == 'en' || saved == 'zh') {
        _lang = saved!;
        return;
      }
      // 首次启动：跟随设备语言
      final device = PlatformDispatcher.instance.locale.languageCode.toLowerCase();
      _lang = device == 'zh' || device == 'zh-cn' || device == 'zh-tw' ? 'zh' : 'en';
    } catch (_) {}
  }

  /// 取文案（支持 {key} 占位替换）
  static String t(String key, [Map<String, String>? args]) {
    final map = _lang == 'en' ? _en : _zh;
    var s = map[key] ?? _zh[key] ?? key;
    if (args != null) {
      args.forEach((k, v) => s = s.replaceAll('{$k}', v));
    }
    return s;
  }
}

